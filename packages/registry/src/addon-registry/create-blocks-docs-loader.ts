import fs from 'fs';
import path from 'path';
import tmp from 'tmp';

export type BlockDocsSource = {
  block: string;
  variation?: string;
  path: string;
};

const DOCS_SUFFIX = '.block.md';
const FRONTMATTER = /^---\r?\n([\s\S]*?)\r?\n---(?:\r?\n|$)/;

/*
 * Reads the `key: value` lines of a Markdown file's frontmatter.
 */
export function parseFrontmatter(markdown: string): Record<string, string> {
  const match = markdown.match(FRONTMATTER);
  if (!match) return {};
  return Object.fromEntries(
    match[1]
      .split(/\r?\n/)
      .map((line) => line.match(/^\s*([\w-]+)\s*:\s*(.*?)\s*$/))
      .filter((entry): entry is RegExpMatchArray => Boolean(entry))
      .map(([, key, value]) => [key, value.replace(/^(['"])(.*)\1$/, '$2')]),
  );
}

/*
 * Removes the frontmatter from a Markdown file.
 */
export function stripFrontmatter(markdown: string): string {
  return markdown.replace(FRONTMATTER, '');
}

function findFiles(dir: string, found: string[] = []): string[] {
  let entries: fs.Dirent[];
  try {
    entries = fs.readdirSync(dir, { withFileTypes: true });
  } catch {
    return found;
  }
  for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name))) {
    if (entry.name.startsWith('.') || entry.name === 'node_modules') continue;
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      findFiles(fullPath, found);
    } else if (entry.isFile() && entry.name.endsWith(DOCS_SUFFIX)) {
      found.push(fullPath);
    }
  }
  return found;
}

/*
 * Finds the block docs (`*.block.md` files whose frontmatter names a `block`,
 * and optionally a `variation`) in the given folders, in order. When two
 * files document the same block or variation, the last one wins, so add-ons
 * listed after core can replace its docs.
 */
export function findBlocksDocs(paths: string[]): BlockDocsSource[] {
  const sources = new Map<string, BlockDocsSource>();
  for (const dir of paths) {
    for (const file of findFiles(dir)) {
      const { block, variation } = parseFrontmatter(
        fs.readFileSync(file, 'utf-8'),
      );
      if (!block) {
        // eslint-disable-next-line no-console
        console.warn(
          `[@plone/registry] ${file} has no "block" in its frontmatter, ignoring it.`,
        );
        continue;
      }
      const key = variation ? `${block}|${variation}` : block;
      sources.delete(key);
      sources.set(key, {
        block,
        ...(variation ? { variation } : {}),
        path: file,
      });
    }
  }
  return [...sources.values()];
}

/*
 * The code of a module that imports every block docs file as a string, with
 * the bundler's `?raw` query, and exports them as a list.
 */
export function getBlocksDocsLoaderCode(sources: BlockDocsSource[]): string {
  const imports = sources.map(
    (source, index) =>
      `import docs${index} from ${JSON.stringify(`${source.path}?raw`)};`,
  );
  const items = sources.map(
    ({ block, variation }, index) =>
      `  { block: ${JSON.stringify(block)}, ${
        variation ? `variation: ${JSON.stringify(variation)}, ` : ''
      }markdown: docs${index} },`,
  );
  return `/*
Don't change this file manually.
It is autogenerated by @plone/registry.
Instead, add or change the *.block.md files of the blocks.
*/
${imports.join('\n')}

export default [
${items.join('\n')}
];
`;
}

/*
 * Writes the block docs loader module for the given folders and returns its
 * path, to be aliased in the bundler and imported only by server code.
 */
export function createBlocksDocsLoader(
  paths: string[],
  { tempInProject }: { tempInProject?: boolean } = {},
): string {
  const loaderPath = tempInProject
    ? path.join(process.cwd(), '.plone', 'registry.blocksDocs.js')
    : tmp.tmpNameSync({ postfix: '.js' });

  fs.mkdirSync(path.dirname(loaderPath), { recursive: true });
  fs.writeFileSync(loaderPath, getBlocksDocsLoaderCode(findBlocksDocs(paths)));
  return loaderPath;
}
