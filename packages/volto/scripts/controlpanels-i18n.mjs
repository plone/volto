#!/usr/bin/env node
/**
 * Brings @plone/controlpanels' translations (i18next JSON catalogs) into
 * Volto's react-intl (gettext) catalogs, as volto-plate does for @plone/plate.
 *
 *   node scripts/controlpanels-i18n.mjs messages
 *     Generates `controlpanelsMessages.ts`, a `defineMessages` file with every
 *     key of the package, so Volto's i18n extraction adds them to
 *     `locales/volto.pot` and the `.po` files (and keeps them there).
 *
 *   node scripts/controlpanels-i18n.mjs po
 *     Fills empty `controlpanels.*` translations in
 *     `locales/<language>/LC_MESSAGES/volto.po` from the package's catalog
 *     for that language. Existing translations win.
 *
 * Both run as part of the `i18n` script.
 */
/* eslint-disable no-console */
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import * as prettier from 'prettier';

const require = createRequire(import.meta.url);
const voltoDir = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '..',
);
const catalogsDir = path.join(
  path.dirname(require.resolve('@plone/controlpanels/package.json')),
  'src',
  'locales',
);
const messagesFile = path.join(
  voltoDir,
  'src/components/manage/Controlpanels/ContentTypesControlpanel/controlpanelsMessages.ts',
);
const localesDir = path.join(voltoDir, 'locales');

/** `{ a: { b: 'B' } }` -> `{ 'a.b': 'B' }` (i18next `.` key separator). */
const flatten = (node, prefix = '', result = {}) => {
  for (const [key, value] of Object.entries(node)) {
    const id = prefix ? `${prefix}.${key}` : key;
    if (value && typeof value === 'object') {
      flatten(value, id, result);
    } else if (typeof value === 'string') {
      result[id] = value;
    }
  }
  return result;
};

/** i18next `{{name}}` -> ICU `{name}`. */
const toIcu = (text) => text.replace(/\{\{\s*(\w+)\s*\}\}/g, '{$1}');

const readCatalog = (language) => {
  const file = path.join(catalogsDir, language, 'common.json');
  if (!fs.existsSync(file)) return undefined;
  return flatten(JSON.parse(fs.readFileSync(file, 'utf8')));
};

async function generateMessages() {
  const catalog = readCatalog('en') ?? {};
  const entries = Object.keys(catalog)
    .sort()
    .map(
      (id) =>
        `  ${JSON.stringify(id)}: { id: ${JSON.stringify(id)}, defaultMessage: ${JSON.stringify(toIcu(catalog[id]))} },`,
    );

  const source = `// Generated by \`scripts/controlpanels-i18n.mjs messages\` from
// @plone/controlpanels' catalogs. Do not edit: change the package's messages.
// It only exists so Volto's i18n extraction picks up the package's keys.
import { defineMessages } from 'react-intl';

export default defineMessages({
${entries.join('\n')}
});
`;

  const options = (await prettier.resolveConfig(messagesFile)) ?? {};
  const formatted = await prettier.format(source, {
    ...options,
    filepath: messagesFile,
  });

  fs.writeFileSync(messagesFile, formatted);
  console.log(
    `Generated ${path.relative(voltoDir, messagesFile)} (${entries.length} messages)`,
  );
}

const unescapePo = (text) => text.replace(/\\"/g, '"').replace(/\\\\/g, '\\');
const escapePo = (text) => text.replace(/\\/g, '\\\\').replace(/"/g, '\\"');

function fillPoFiles() {
  for (const language of fs.readdirSync(localesDir).sort()) {
    const poFile = path.join(localesDir, language, 'LC_MESSAGES', 'volto.po');
    // English, and its variants, fall back to the default messages.
    if (language.split('_')[0] === 'en' || !fs.existsSync(poFile)) continue;

    // Volto uses `pt_BR`, i18next `pt-BR`; also try the base language.
    const catalog = [
      language,
      language.replace('_', '-'),
      language.split('_')[0],
    ].reduce((found, candidate) => found ?? readCatalog(candidate), undefined);
    if (!catalog) continue;

    let filled = 0;
    const po = fs
      .readFileSync(poFile, 'utf8')
      .replace(
        /^msgid "(controlpanels\.(?:[^"\\]|\\.)*)"\nmsgstr ""$/gm,
        (match, msgid) => {
          const translation = catalog[unescapePo(msgid)];
          if (!translation) return match;
          filled += 1;
          return `msgid "${msgid}"\nmsgstr "${escapePo(toIcu(translation))}"`;
        },
      );

    if (!filled) continue;
    fs.writeFileSync(poFile, po);
    console.log(`Filled ${filled} control panel translations in ${language}`);
  }
}

const command = process.argv[2];

if (command === 'messages') {
  await generateMessages();
} else if (command === 'po') {
  fillPoFiles();
} else {
  console.error('Usage: controlpanels-i18n.mjs <messages|po>');
  process.exit(1);
}
